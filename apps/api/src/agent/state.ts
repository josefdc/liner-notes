/**
 * Agent State Definition
 *
 * Defines the state that flows through the LangGraph workflow.
 * Maps to the frontend TrackData interface.
 */

import { Annotation } from "@langchain/langgraph";
import type { SearchCandidate, TrackData } from "./schema.js";

// =============================================================================
// TypeScript Interfaces (matching frontend types)
// =============================================================================

export interface SongSegment {
  label: string;
  start: number; // percentage 0-100
  end: number; // percentage 0-100
  color: string;
}

export interface FactoidEntity {
  id: string;
  text: string;
  type: "synth" | "producer" | "sample" | "technique" | "artist" | "album" | "year";
  searchQuery?: string;
}

export interface Factoid {
  id: string;
  title: string;
  content: string;
  type: "production" | "trivia" | "lyrics" | "credits" | "sample" | "curiosity" | "connection";
  /** Clickable entities mentioned in the factoid (artists, songs, albums) */
  entities?: FactoidEntity[];
}

export interface Sample {
  time: number;
  description: string;
}

export interface ProductionCredits {
  producers: string[];
  writers: string[];
  engineers?: string[];
  label?: string;
}

export interface GenealogyNode {
  id: string;
  group: number;
  label: string;
  img: string;
  size: number;
  // Audio preview for hover-to-play
  previewUrl?: string;
  spotifyId?: string;
  // Parsed metadata for navigation
  trackTitle?: string;
  trackArtist?: string;
}

export interface GenealogyLink {
  source: string;
  target: string;
  value: number;
  // Semantic relationship type
  type?: "sample" | "cover" | "remix" | "producer" | "influence";
}

// =============================================================================
// Intermediate Data Types (collected during workflow)
// =============================================================================

export interface SpotifyData {
  id: string;
  title: string;
  artist: string;
  artistIds: string[];
  album: string;
  releaseDate: string;
  coverUrl: string;
  popularity: number;
  duration: string;
  durationMs: number;
  explicit: boolean;
  spotifyUrl: string;
  previewUrl: string | null;
}

export interface KeyMoment {
  time: number; // Time in seconds
  type: "energy_peak" | "energy_drop" | "onset" | "harmonic_change" | "silence";
  intensity: number; // 0-1 scale
  description: string;
}

export interface AudioFeatures {
  bpm: number;
  key: string;
  energy: number;
  valence: number;
  danceability: number;
  acousticness: number;
  instrumentalness: number;
  /** Reliability of the analysis: 'high' for real librosa analysis, 'low' for estimation */
  confidence: "low" | "high";
  /** Key moments detected in the audio (drops, peaks, transitions) */
  keyMoments?: KeyMoment[];
}

export interface ResearchData {
  samples: string[];
  productionTrivia: string[];
  songMeaning: string[];
  relatedArtists: string[];
  /** Artist collaborators from MusicBrainz */
  collaborators?: string[];
  /** Top tracks from the same artist (from Spotify) */
  artistTopTracks?: Array<{ id: string; title: string; album: string; popularity: number }>;
  /** Genre/style tags from Last.fm (track + artist combined) */
  lastfmTags?: string[];
  /** Similar tracks from Last.fm */
  lastfmSimilarTracks?: string[];
  /** Similar artists from Last.fm */
  lastfmSimilarArtists?: string[];
  /** Artist biography snippet from Last.fm */
  lastfmArtistBio?: string;
  /** Similar artists from ListenBrainz (open-source listening data) */
  listenbrainzSimilarArtists?: string[];
}

// =============================================================================
// HITL Configuration Types
// =============================================================================

/**
 * Configuration for Human-in-the-Loop disambiguation behavior
 */
export interface HITLConfig {
  /** Popularity threshold for auto-selection (0-100, default: 85) */
  disambiguationThreshold: number;
  /** Minimum popularity gap ratio to skip disambiguation (0-1, default: 0.3) */
  popularityGap: number;
  /** Maximum candidates to show user (default: 5) */
  maxCandidates: number;
}

/**
 * Default HITL configuration values
 */
export const DEFAULT_HITL_CONFIG: HITLConfig = {
  disambiguationThreshold: 85,
  popularityGap: 0.3,
  maxCandidates: 5,
};

// =============================================================================
// Research Subgraph Types
// =============================================================================

/**
 * Research plan generated by the LLM research manager
 */
export interface ResearchPlan {
  /** Next search action to perform */
  nextAction:
    | "search_samples"
    | "search_production"
    | "search_meaning"
    | "search_general"
    | "search_lyrics"
    | "search_annotations"
    | "search_musicbrainz"
    | "search_artist_collaborators"
    | "search_artist_top_tracks"
    | "search_lastfm_tags"
    | "search_lastfm_similar_tracks"
    | "search_lastfm_similar_artists"
    | "search_lastfm_artist_info"
    | "search_listenbrainz_similar"
    | "done";
  /** Specific search query (if not done) */
  query?: string;
  /** Reasoning for this decision */
  reasoning: string;
}

/**
 * A research lead discovered during analysis
 */
export interface ResearchLead {
  /** Unique identifier */
  id: string;
  /** Type of lead */
  type: "sample" | "influence" | "producer" | "collaborator" | "event";
  /** Search query to explore this lead */
  query: string;
  /** Priority level */
  priority: "high" | "medium" | "low";
  /** Why this lead is interesting */
  reason: string;
  /** Whether this lead has been explored */
  explored: boolean;
}

// =============================================================================
// Sonic Agent State (the real state used by the graph)
// =============================================================================

/**
 * The main state that flows through the LangGraph workflow.
 *
 * Workflow: scout → [clarification?] → parallel(engineer, historian) → composer → END
 */
export const SonicAgentState = Annotation.Root({
  // Input
  songQuery: Annotation<string>({
    reducer: (_, next) => next,
    default: () => "",
  }),

  // Search candidates (for human disambiguation)
  candidates: Annotation<SearchCandidate[] | null>({
    reducer: (_, next) => next,
    default: () => null,
  }),

  // Selected track ID (after disambiguation or auto-select)
  selectedTrackId: Annotation<string | null>({
    reducer: (_, next) => next,
    default: () => null,
  }),

  // Spotify metadata
  spotifyData: Annotation<SpotifyData | null>({
    reducer: (_, next) => next,
    default: () => null,
  }),

  // Audio features (from engineer)
  audioFeatures: Annotation<AudioFeatures | null>({
    reducer: (_, next) => next,
    default: () => null,
  }),

  // Research data (from historian)
  // Uses accumulation reducer: [...prev.X, ...next.X] (not replace) because
  // engineerNode and historianNode run in parallel and both contribute research data.
  researchData: Annotation<ResearchData>({
    reducer: (prev, next) => ({
      samples: [...prev.samples, ...next.samples],
      productionTrivia: [...prev.productionTrivia, ...next.productionTrivia],
      songMeaning: [...prev.songMeaning, ...next.songMeaning],
      relatedArtists: [...prev.relatedArtists, ...next.relatedArtists],
      collaborators: [...(prev.collaborators || []), ...(next.collaborators || [])],
      artistTopTracks: [...(prev.artistTopTracks || []), ...(next.artistTopTracks || [])],
      lastfmTags: [...(prev.lastfmTags || []), ...(next.lastfmTags || [])],
      lastfmSimilarTracks: [
        ...(prev.lastfmSimilarTracks || []),
        ...(next.lastfmSimilarTracks || []),
      ],
      lastfmSimilarArtists: [
        ...(prev.lastfmSimilarArtists || []),
        ...(next.lastfmSimilarArtists || []),
      ],
      lastfmArtistBio: next.lastfmArtistBio || prev.lastfmArtistBio,
      listenbrainzSimilarArtists: [
        ...(prev.listenbrainzSimilarArtists || []),
        ...(next.listenbrainzSimilarArtists || []),
      ],
    }),
    default: () => ({
      samples: [],
      productionTrivia: [],
      songMeaning: [],
      relatedArtists: [],
      collaborators: [],
      artistTopTracks: [],
      lastfmTags: [],
      lastfmSimilarTracks: [],
      lastfmSimilarArtists: [],
      lastfmArtistBio: undefined,
      listenbrainzSimilarArtists: [],
    }),
  }),

  // Final output
  trackData: Annotation<TrackData | null>({
    reducer: (_, next) => next,
    default: () => null,
  }),

  // Error tracking
  error: Annotation<string | null>({
    reducer: (_, next) => next,
    default: () => null,
  }),

  // Status messages for streaming
  statusMessages: Annotation<string[]>({
    reducer: (prev, next) => [...prev, ...next],
    default: () => [],
  }),

  // HITL configuration (configurable thresholds for disambiguation)
  hitlConfig: Annotation<HITLConfig>({
    reducer: (_, next) => next,
    default: () => DEFAULT_HITL_CONFIG,
  }),
});

export type SonicAgentStateType = typeof SonicAgentState.State;

